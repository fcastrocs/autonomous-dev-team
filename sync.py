def compile_skills(project: dict, guardrails_block: str, base_dir: Path, skills_dir: Path, scope: str) -> dict:
    """Compile canonical skills for native discovery and explicit Codex prompts."""
    outputs = {}
    if not skills_dir.exists():
        return outputs
        
    for skill_path in skills_dir.iterdir():
        if not skill_path.is_dir():
            continue
        skill_name = skill_path.name
        
        for file_path in skill_path.rglob("*"):
            if not file_path.is_file():
                continue
            
            content = read_canonical_source(base_dir, file_path.relative_to(base_dir))
            content = interpolate_prompt(content, project, guardrails_block)
            rel_path = file_path.relative_to(skill_path)
            
            if file_path.name == "SKILL.md":
                parts = content.split("---", 2)
                if len(parts) >= 3:
                    frontmatter = f"---{parts[1]}---\n"
                    body = parts[2].lstrip()
                    content = f"{frontmatter}\n{AUTO_GEN_HEADER_MD}\n{body}"
                else:
                    content = f"{AUTO_GEN_HEADER_MD}\n{content}"
            
            if scope in ("all", "antigravity", "agy", "codex"):
                outputs[base_dir / ".agents" / "skills" / skill_name / rel_path] = content
            if scope in ("all", "claude"):
                outputs[base_dir / ".claude" / "skills" / skill_name / rel_path] = content
            if scope in ("all", "codex") and file_path.name == "SKILL.md" and rel_path == Path("SKILL.md"):
                outputs[base_dir / ".codex" / "prompts" / f"{skill_name}.md"] = content
                
    return outputs

def generate_project_config_toml(project_name: str, source_dir: Path = None, active_provider: str = "all") -> str:
    """Render the canonical config for a new repo: project name set, repo-owned [project] fields left blank."""
    base_dir = source_dir or resolve_base_dir()
    canonical = read_canonical_source(base_dir, Path(CONFIG_NAME))
    
    provider_val = "antigravity" if active_provider == "agy" else active_provider
    lines = canonical.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("active_provider ="):
            lines[i] = f'active_provider = "{provider_val}"\n'
            break
    canonical = "".join(lines)
    
    tomllib.loads(canonical)
    values = {
        "name": project_name,
        "description": "",
        "focused_test_cmd": "",
        "full_test_cmd": "",
        "build_cmd": "",
    }
    lines = canonical.splitlines(keepends=True)
    project_start = next((i for i, line in enumerate(lines) if line.strip() == "[project]"), None)
    if project_start is None:
        raise ValueError(f"Canonical {CONFIG_NAME} is missing [project]")
    project_end = next(
        (i for i in range(project_start + 1, len(lines)) if lines[i].strip().startswith("[")),
        len(lines),
    )
    replacements = []
    for key, value in values.items():
        starts = [
            i for i in range(project_start + 1, project_end)
            if lines[i].split("=", 1)[0].strip() == key and "=" in lines[i]
        ]
        if len(starts) != 1:
            raise ValueError(f"Canonical {CONFIG_NAME} must define [project].{key} exactly once")
        start = starts[0]
        end = None
        for candidate_end in range(start + 1, project_end + 1):
            try:
                parsed = tomllib.loads("[project]\n" + "".join(lines[start:candidate_end]))
            except tomllib.TOMLDecodeError:
                continue
            if key in parsed.get("project", {}):
                end = candidate_end
                break
        if end is None:
            raise ValueError(f"Canonical {CONFIG_NAME} has an invalid [project].{key} assignment")
        replacements.append((start, end, f"{key} = {json.dumps(value, ensure_ascii=False)}\n"))
    for start, end, replacement in reversed(replacements):
        lines[start:end] = [replacement]
    rendered = "".join(lines)
    tomllib.loads(rendered)
    return rendered

def generate_all_outputs(base_dir: Path, provider_override: str = None) -> dict:
    """Generates a dict of Path -> content for all target provider files without writing them to disk."""
    config_path = resolve_config_path(base_dir)
    agents_dir = resolve_agents_dir(base_dir)
    config = load_config(config_path)
    project = dict(config.get("project", {}))
    project["forbidden_paths"] = get_effective_forbidden_paths(project)
    provider = provider_override or config.get("active_provider", "all")
    
    guardrails_block = build_project_guardrails(project)
    
    all_outputs = {}
    if provider in ("all", "claude", "antigravity", "agy"):
        all_outputs[base_dir / "AGENTS.md"] = compile_agents_md(config, project, guardrails_block, base_dir)
    if provider in ("all", "codex"):
        all_outputs.update(compile_codex(config, project, guardrails_block, base_dir, agents_dir))
    if provider in ("all", "claude"):
        all_outputs.update(compile_claude(config, project, guardrails_block, base_dir, agents_dir))
    if provider in ("all", "antigravity", "agy"):
        all_outputs.update(compile_antigravity(config, project, guardrails_block, base_dir, agents_dir))
        all_outputs[base_dir / ".agents" / "hooks.json"] = compile_antigravity_hooks(base_dir)
        
    skills_dir = resolve_skills_dir(base_dir)
    all_outputs.update(compile_skills(project, guardrails_block, base_dir, skills_dir, provider))
        
    return all_outputs

def run_sync(base_dir: Path, provider_override: str = None):
    """Synchronizes all target provider configurations, writes generated files, prunes stale artifacts, and updates the manifest."""
    print("Synchronizing Multi-Provider Autonomous Agent Protocol...")
    outputs = generate_all_outputs(base_dir, provider_override)
    manifest_path = resolve_manifest_path(base_dir)
    previous = []
    if manifest_path.exists():
        try:
            previous = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            previous = []
    elif (base_dir / MANIFEST_NAME).exists():
        try:
            previous = json.loads((base_dir / MANIFEST_NAME).read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            previous = []
    current = {str(path.relative_to(base_dir)) for path in outputs}
    scope = provider_scope(base_dir, provider_override)
    preserved = set() if scope == "all" else {
        path for path in previous if not provider_matches_scope(output_provider(path), scope)
    }
    for relative in sorted(set(previous) - current - preserved):
        stale = managed_path(base_dir, relative)
        if stale and stale.is_file():
            content = stale.read_text(encoding="utf-8")
            if (
                "AUTO-GENERATED BY sync.py" in content
                or (output_provider(relative) == "claude" and relative.startswith(".claude/agents/"))
                or (output_provider(relative) == "codex" and relative.startswith(".codex/agents/"))
                or (output_provider(relative) == "antigravity" and relative.startswith(".agents/agents/"))
            ):
                stale.unlink()
                try:
                    parent = stale.parent
                    if parent != base_dir and parent.is_dir() and not any(parent.iterdir()):
                        parent.rmdir()
                except OSError:
                    pass
    
    codex_agent_count = 0
    claude_agent_count = 0
    antigravity_agent_count = 0
    agents_md_updated = False
    
    for fpath, content in outputs.items():
        fpath.parent.mkdir(parents=True, exist_ok=True)
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(content)
        if ".codex/agents" in fpath.as_posix():
            codex_agent_count += 1
        elif ".claude/agents" in fpath.as_posix():
            claude_agent_count += 1
        elif ".agents/agents" in fpath.as_posix() and fpath.name == "agent.md":
            antigravity_agent_count += 1
        elif fpath.name == "AGENTS.md":
            agents_md_updated = True
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps({"schema": SCHEMA_NAME, "version": SCHEMA_VERSION,
                                         "files": sorted(current | preserved)}, indent=2) + "\n", encoding="utf-8")
    if manifest_path != (base_dir / MANIFEST_NAME) and (base_dir / MANIFEST_NAME).is_file():
        try:
            (base_dir / MANIFEST_NAME).unlink()
        except OSError:
            pass
            
    if agents_md_updated:
        print("  ✓ Universal: Generated AGENTS.md")
    if codex_agent_count > 0:
        print(f"  ✓ Codex: Compiled {codex_agent_count} agents into .codex/")
    if claude_agent_count > 0:
        print(f"  ✓ Claude Code: Compiled {claude_agent_count} agents into .claude/agents/")
    if antigravity_agent_count > 0:
        print(f"  ✓ Antigravity: Compiled {antigravity_agent_count} agents into .agents/agents/")
    
    skills_count = sum(1 for p in current if "/skills/" in str(p) or "/prompts/" in str(p))
    if skills_count > 0:
        print(f"  ✓ Skills: Compiled canonical skills to providers")

    for candidate in (
        base_dir / ENCAPSULATED_DIR_NAME / "__pycache__",
        base_dir / ENCAPSULATED_DIR_NAME / INTERNAL_DIR_NAME / "__pycache__",
    ):
        if candidate.is_dir() and not candidate.is_symlink():
            try:
                shutil.rmtree(candidate)
            except OSError:
                pass

    print("✓ Synchronization complete.\n")

def run_check(base_dir: Path, provider_override: str = None, quiet: bool = False) -> int:
    """Checks generated files and their ownership manifest. Returns 0 if matching."""
    outputs = generate_all_outputs(base_dir, provider_override)
    mismatched = []
    missing = []
    stale = []
    budget_errors = []
    leakage_errors = []
    
    for fpath, expected_content in outputs.items():
        if not fpath.exists():
            missing.append(fpath.relative_to(base_dir))
        else:
            with open(fpath, "r", encoding="utf-8") as f:
                actual_content = f.read()
            if actual_content != expected_content:
                mismatched.append(fpath.relative_to(base_dir))
    manifest_path = resolve_manifest_path(base_dir)
    if not manifest_path.exists():
        fallback = base_dir / MANIFEST_NAME
        if fallback.exists():
            manifest_path = fallback
        else:
            missing.append(manifest_path.relative_to(base_dir))
    if manifest_path.exists():
        try:
            owned = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            owned = []
        expected = {str(path.relative_to(base_dir)) for path in outputs}
        scope = provider_scope(base_dir, provider_override)
        stale = [Path(path) for path in owned
                 if path not in expected and provider_matches_scope(output_provider(path), scope)
                 and managed_path(base_dir, path)
                 and managed_path(base_dir, path).exists()]
                
    # 1. Token Budget Enforcement
    ambient_file = base_dir / "AGENTS.md"
    ambient_content = ""
    if ambient_file.is_file():
        ambient_content = ambient_file.read_text(encoding="utf-8")
    elif ambient_file in outputs:
        ambient_content = outputs[ambient_file]

    ambient_chars = len(ambient_content)
    ambient_tokens = estimate_tokens(ambient_chars)
    if ambient_content and (ambient_chars > MAX_AMBIENT_CHARS or ambient_tokens > MAX_AMBIENT_TOKENS):
        budget_errors.append(
            f"Ambient file AGENTS.md exceeds budget: {ambient_chars} chars (~{ambient_tokens} tokens) "
            f"(limit: {MAX_AMBIENT_CHARS} chars / {MAX_AMBIENT_TOKENS} tokens)"
        )

    for fpath, expected_content in outputs.items():
        rel = fpath.relative_to(base_dir)
        is_subagent = False
        if len(rel.parts) == 4 and rel.parts[:2] == (".agents", "agents") and rel.name == "agent.md":
            if rel.parts[2] != "orchestrator":
                is_subagent = True
        elif len(rel.parts) == 3 and rel.parts[:2] == (".claude", "agents") and rel.suffix == ".md":
            if rel.stem != "orchestrator":
                is_subagent = True
        elif len(rel.parts) == 3 and rel.parts[:2] == (".codex", "agents") and rel.suffix == ".toml":
            if rel.stem != "orchestrator":
                is_subagent = True

        if is_subagent:
            actual_content = fpath.read_text(encoding="utf-8") if fpath.is_file() else expected_content
            role_chars = len(actual_content)
            role_tokens = estimate_tokens(role_chars)
            if role_chars > MAX_ROLE_CHARS or role_tokens > MAX_ROLE_TOKENS:
                budget_errors.append(
                    f"Subagent role {rel} exceeds budget: {role_chars} chars (~{role_tokens} tokens) "
                    f"(limit: {MAX_ROLE_CHARS} chars / {MAX_ROLE_TOKENS} tokens)"
                )
            start_cost_chars = ambient_chars + role_chars
            start_cost_tokens = estimate_tokens(start_cost_chars)
            if start_cost_chars > MAX_STARTUP_CHARS or start_cost_tokens > MAX_STARTUP_TOKENS:
                budget_errors.append(
                    f"Subagent startup cost for {rel} exceeds budget: {start_cost_chars} chars (~{start_cost_tokens} tokens) "
                    f"(limit: {MAX_STARTUP_CHARS} chars / {MAX_STARTUP_TOKENS} tokens)"
                )

    # 2. Data-Driven Leakage Scanner
    files_to_scan = []
    if ambient_file.is_file():
        files_to_scan.append((ambient_file, ambient_content))
    elif ambient_file in outputs:
        files_to_scan.append((ambient_file, outputs[ambient_file]))

    for fpath, expected_content in outputs.items():
        rel = fpath.relative_to(base_dir)
        is_subagent = False
        if len(rel.parts) == 4 and rel.parts[:2] == (".agents", "agents") and rel.name == "agent.md":
            if rel.parts[2] != "orchestrator":
                is_subagent = True
        elif len(rel.parts) == 3 and rel.parts[:2] == (".claude", "agents") and rel.suffix == ".md":
            if rel.stem != "orchestrator":
                is_subagent = True
        elif len(rel.parts) == 3 and rel.parts[:2] == (".codex", "agents") and rel.suffix == ".toml":
            if rel.stem != "orchestrator":
                is_subagent = True

        if is_subagent:
            actual_content = fpath.read_text(encoding="utf-8") if fpath.is_file() else expected_content
            files_to_scan.append((fpath, actual_content))

    for target_path, content in files_to_scan:
        rel_target = target_path.relative_to(base_dir)
        for marker in LEAKAGE_MARKERS:
            if marker in content:
                leakage_errors.append(f"Forbidden leakage marker '{marker}' found in {rel_target}")

    if not missing and not mismatched and not stale and not budget_errors and not leakage_errors:
        if not quiet:
            print(f"✓ All provider configurations are in sync with {CONFIG_NAME} and agents/.")
        return 0
    else:
        if not quiet:
            if missing or mismatched or stale:
                print("Error: Provider configurations are out of sync!")
                if missing:
                    print("  Missing files:")
                    for m in missing:
                        print(f"    - {m}")
                if mismatched:
                    print("  Out-of-date files:")
                    for m in mismatched:
                        print(f"    - {m}")
                if stale:
                    print("  Stale managed files:")
                    for item in stale:
                        print(f"    - {item}")
            if budget_errors:
                print("Error: Token budget exceeded!")
                for b in budget_errors:
                    print(f"    - {b}")
            if leakage_errors:
                print("Error: Orchestrator leakage detected!")
                for l in leakage_errors:
                    print(f"    - {l}")
            print("\nRun './sync.py' to regenerate provider files.")
        return 1


def run_verify(base_dir: Path, hook_mode: bool = False) -> int:
    """
    Executes the configured [project] build_cmd and full_test_cmd, skipping any left blank.
    Exits 0 if all pass, 1 if any fail.
    When hook_mode is True, formats stdout as an Antigravity Stop hook JSON response.
    """
    config_path = resolve_config_path(base_dir)
    config = load_config(config_path)
    project = config.get("project", {})
    verify_cmds = [c for c in [project.get("build_cmd", ""), project.get("full_test_cmd", "")] if c]

    all_passed = True
    for cmd in verify_cmds:
        res = subprocess.run(cmd, shell=True, cwd=str(base_dir), capture_output=hook_mode)
        if res.returncode != 0:
            all_passed = False
            break

    if hook_mode:
        if all_passed:
            print(json.dumps({"decision": "allow"}))
            return 0
        else:
            print(json.dumps({
                "decision": "continue",
                "reason": "Verification commands failed with non-zero exit code. Fix failures before stopping."
            }))
            return 0
    else:
        return 0 if all_passed else 1

