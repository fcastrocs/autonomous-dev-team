def resolve_escalation_ladders(config: dict, provider: str) -> dict:
    """Return role -> [(tier, model), ...] starting at the role's base tier, from [agents.<role>].escalation."""
    prov = resolve_provider(provider)
    models_cfg = config.get("models", {})
    agents = provider_agents(config, prov)
    ladders = {}
    for role, agent_cfg in config.get("agents", {}).items():
        escalation = agent_cfg.get("escalation") or []
        if not escalation:
            continue
        steps = [(agents[role]["tier"], agents[role]["model"])]
        for tier in escalation:
            steps.append((tier, models_cfg.get(tier, {}).get(prov, "inherit")))
        ladders[role] = steps
    return ladders


def resolve_adaptive_steps(config: dict, provider: str) -> dict:
    """Resolve declared steps, collapsing changes the provider cannot deliver."""
    prov = resolve_provider(provider)
    delivery = config.get("reasoning_policy", {}).get("providers", {}).get(prov, {}).get("effort_delivery", "unsupported")
    result = {}
    for role, agent in config.get("agents", {}).items():
        if "adaptive_steps" not in agent:
            continue
        steps = []
        previous = None
        for step in agent["adaptive_steps"]:
            model = config["models"][step["tier"]].get(prov, "inherit")
            effective = (model, step["effort"] if delivery == "native" else None)
            if effective == previous:
                continue
            steps.append(dict(step, model=model, delivery=delivery))
            previous = effective
        result[role] = steps
    return result


def effort_delivery(config: dict, provider: str) -> str:
    """Describe declared delivery without inventing a provider capability."""
    return config.get("reasoning_policy", {}).get("providers", {}).get(resolve_provider(provider), {}).get("effort_delivery", "unsupported")


def render_escalation_ladder(config: dict, provider: str) -> str:
    """Render the provider-specific escalation ladder for root orchestrator adapters."""
    ladders = resolve_escalation_ladders(config, provider)
    if not ladders and not resolve_adaptive_steps(config, provider):
        return ""
    lines = [
        "## Model escalation ladder",
        "",
        "Dispatch each role on its first step. Move one step up only under the adaptive model escalation rules; record the reason in the dispatch and completion report.",
        "",
    ]
    for role, steps in ladders.items():
        if role in resolve_adaptive_steps(config, provider):
            continue
        chain = " -> ".join(f"`{tier}` (`{model}`)" for tier, model in steps)
        lines.append(f"- `{role}`: {chain}")
    for role, steps in resolve_adaptive_steps(config, provider).items():
        chain = " -> ".join(f"`{s['tier']}` (`{s['model']}`, effort `{s['effort']}`{', exceptional' if s.get('exceptional') else ''})" for s in steps)
        delivery = steps[0]["delivery"]
        lines.append(f"- `{role}`: {chain}. Effort delivery: {delivery}; ineffective steps collapsed.")
        if delivery == "native":
            lines.append("Pass model AND reasoning_effort runtime overrides when supported; otherwise report the unsupported override, never claim enforcement.")
        else:
            lines.append("Effort is advisory or unsupported; no native reasoning override is enforced.")
    if resolve_adaptive_steps(config, provider):
        lines.append(f"Reset unrelated slices; max {config['reasoning_policy']['max_repairs']} total repair attempts across all steps. Exceptional steps require prior-step failure evidence.")
    return "\n".join(lines)


def validate_model_tiers(cfg: dict) -> list:
    """Return configuration errors for tier references missing from [models]."""
    models_cfg = cfg.get("models", {})
    errors = []
    policy = cfg.get("reasoning_policy", {})
    if not isinstance(policy, dict):
        return ["reasoning_policy must be a table"]
    refs = [("orchestrator", cfg.get("orchestrator", {}).get("tier"))]
    for role, agent_cfg in cfg.get("agents", {}).items():
        refs.append((f"agents.{role}", agent_cfg.get("tier")))
        steps = agent_cfg.get("adaptive_steps")
        if steps is not None:
            if not isinstance(steps, list) or not steps:
                errors.append(f"agents.{role}.adaptive_steps must be a nonempty list")
            else:
                seen = set()
                for index, step in enumerate(steps):
                    if not isinstance(step, dict):
                        errors.append(f"agents.{role}.adaptive_steps entries must be tables")
                        continue
                    refs.append((f"agents.{role}.adaptive_steps", step.get("tier")))
                    if not isinstance(step.get("tier"), str):
                        errors.append(f"agents.{role}.adaptive_steps requires tier")
                    efforts = policy.get("efforts", [])
                    if not isinstance(efforts, list) or not isinstance(step.get("effort"), str) or step.get("effort") not in efforts:
                        errors.append(f"agents.{role}.adaptive_steps has invalid effort")
                    if not isinstance(step.get("exceptional", False), bool):
                        errors.append(f"agents.{role}.adaptive_steps exceptional must be boolean")
                    if step.get("exceptional") and index != len(steps) - 1:
                        errors.append(f"agents.{role}.adaptive_steps exceptional step must be last")
                    if isinstance(step.get("tier"), str) and isinstance(step.get("effort"), str):
                        key = (step["tier"], step["effort"])
                        if key in seen:
                            errors.append(f"agents.{role}.adaptive_steps contains duplicate step")
                        seen.add(key)
                if isinstance(steps[0], dict) and (steps[0].get("tier") != agent_cfg.get("tier") or steps[0].get("effort") != agent_cfg.get("reasoning_effort") or steps[0].get("exceptional", False)):
                    errors.append(f"agents.{role}.adaptive_steps must start at the configured tier and effort")
        escalation = agent_cfg.get("escalation", [])
        if not isinstance(escalation, list):
            errors.append(f"agents.{role}.escalation must be a list of tier names")
            continue
        refs.extend((f"agents.{role}.escalation", tier) for tier in escalation)
    for where, tier in refs:
        if tier is not None and (not isinstance(tier, str) or tier not in models_cfg):
            errors.append(f"{where} references unknown model tier '{tier}' (defined: {', '.join(models_cfg) or 'none'})")
    policy = cfg.get("reasoning_policy")
    if policy is not None:
        if not isinstance(policy, dict):
            return errors + ["reasoning_policy must be a table"]
        if not isinstance(policy.get("max_repairs"), int) or isinstance(policy.get("max_repairs"), bool) or policy["max_repairs"] < 1:
            errors.append("reasoning_policy.max_repairs must be a positive integer")
        efforts = policy.get("efforts")
        if not isinstance(efforts, list) or not efforts or any(not isinstance(e, str) or not e for e in efforts):
            errors.append("reasoning_policy.efforts must be a nonempty list of strings")
        providers = policy.get("providers", {})
        if not isinstance(providers, dict):
            return errors + ["reasoning_policy.providers must be a table"]
        for prov, capability in providers.items():
            if not isinstance(capability, dict) or capability.get("effort_delivery") not in ("native", "advisory", "unsupported"):
                errors.append(f"reasoning_policy.providers.{prov} has invalid effort_delivery")
    return errors


def load_config(config_path: Path) -> dict:
    if not config_path.exists():
        sys.exit(f"Error: Configuration file '{config_path}' not found.\nRun './sync.py --init' to generate one.")
    with open(config_path, "rb") as f:
        cfg = tomllib.load(f)
    if cfg.get("schema_version") != 2:
        sys.exit("Error: Config schema v1 is unsupported. Update to schema_version = 2.")
    tier_errors = validate_model_tiers(cfg)
    if tier_errors:
        sys.exit("Error: Invalid model tier configuration:\n  - " + "\n  - ".join(tier_errors))
    return cfg

