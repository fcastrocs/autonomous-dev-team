def provider_agents(config: dict, provider: str) -> dict:
    """Resolve configured agents dynamically from Schema v2 models and agents tables."""
    prov = resolve_provider(provider)
    models_cfg = config.get("models", {})
    raw_agents = config.get("agents", {})
    resolved = {}
    for role, agent_cfg in raw_agents.items():
        tier = agent_cfg.get("tier", "balanced")
        reasoning_effort = agent_cfg.get("reasoning_effort", "medium")
        model = agent_cfg.get("model") or models_cfg.get(tier, {}).get(prov, "inherit")
        effort = resolve_reasoning_for_provider(prov, model, reasoning_effort)

        agent_dict = dict(agent_cfg)
        agent_dict["model"] = model
        agent_dict["tier"] = tier
        agent_dict["reasoning_effort"] = reasoning_effort
        if prov == "claude":
            agent_dict["thinking"] = effort
        elif prov in ("antigravity", "agy"):
            agent_dict["reasoning"] = effort
        resolved[role] = agent_dict
    return resolved


