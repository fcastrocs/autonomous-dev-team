def resolve_base_dir(dir_arg: str | Path | None = None) -> Path:
    """Resolves base directory. If inside .autonomous-dev-team, resolves to parent project root."""
    if dir_arg:
        p = Path(dir_arg).resolve()
        if p.name == INTERNAL_DIR_NAME and p.parent.name == ENCAPSULATED_DIR_NAME:
            return p.parent.parent
        if p.name == ENCAPSULATED_DIR_NAME:
            return p.parent
        return p
    script_parent = Path(__file__).resolve().parent
    if script_parent.name == INTERNAL_DIR_NAME and script_parent.parent.name == ENCAPSULATED_DIR_NAME:
        return script_parent.parent.parent
    if script_parent.name == ENCAPSULATED_DIR_NAME:
        return script_parent.parent
    return script_parent


def resolve_agents_dir(base_dir: Path) -> Path:
    nested_internal = base_dir / ENCAPSULATED_DIR_NAME / INTERNAL_DIR_NAME / "agents"
    if nested_internal.is_dir():
        return nested_internal
    nested = base_dir / ENCAPSULATED_DIR_NAME / "agents"
    if nested.is_dir():
        return nested
    return base_dir / "agents"


def resolve_skills_dir(base_dir: Path) -> Path:
    nested_internal = base_dir / ENCAPSULATED_DIR_NAME / INTERNAL_DIR_NAME / "skills"
    if nested_internal.is_dir():
        return nested_internal
    nested = base_dir / ENCAPSULATED_DIR_NAME / "skills"
    if nested.is_dir():
        return nested
    return base_dir / "skills"


def resolve_manifest_path(base_dir: Path) -> Path:
    nested = base_dir / ENCAPSULATED_DIR_NAME
    if nested.is_dir():
        return nested / CLIENT_MANIFEST_NAME
    return base_dir / MANIFEST_NAME


def is_self_repo(path: Path) -> bool:
    return (
        (path / "sync.py").is_file()
        and (path / "install.py").is_file()
        and (path / "tests" / "test_sync.py").is_file()
    )


def read_canonical_source(base_dir: Path, relative_path: Path) -> str:
    candidates = []
    if relative_path == Path(CONFIG_NAME):
        candidates.append(base_dir / ENCAPSULATED_DIR_NAME / CLIENT_CONFIG_NAME)
    candidates.append(base_dir / ENCAPSULATED_DIR_NAME / INTERNAL_DIR_NAME / relative_path)
    candidates.append(base_dir / ENCAPSULATED_DIR_NAME / relative_path)
    candidates.append(base_dir / relative_path)
    for p in candidates:
        if p.is_file():
            return p.read_text(encoding="utf-8")
    raise FileNotFoundError(f"Required canonical source is missing: {base_dir / relative_path}")


def compile_orchestrator_protocol(base_dir: Path, project: dict, guardrails_block: str) -> str:
    source = read_canonical_source(base_dir, ORCHESTRATOR_PROTOCOL)
    return interpolate_prompt(source, project, guardrails_block).strip()


def provider_agents(config: dict, provider: str) -> dict:
    """Return configured agents."""
    return dict(config.get(provider, {}).get("agents", {}))

def load_config(config_path: Path) -> dict:
    if not config_path.exists():
        sys.exit(f"Error: Configuration file '{config_path}' not found.\nRun './sync.py --init' to generate one.")
    with open(config_path, "rb") as f:
        return tomllib.load(f)

def resolve_config_path(base_dir: Path) -> Path:
    candidates = [
        base_dir / ENCAPSULATED_DIR_NAME / CLIENT_CONFIG_NAME,
        base_dir / ENCAPSULATED_DIR_NAME / CONFIG_NAME,
        base_dir / CONFIG_NAME,
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    preferred = candidates[0] if (base_dir / ENCAPSULATED_DIR_NAME).is_dir() else candidates[2]
    sys.exit(f"Error: Configuration file '{preferred}' not found.\nRun './sync.py --init' to generate one.")

def managed_path(base_dir: Path, relative: str):
    """Return a lexical in-project path only when no path component is a symlink."""
    entry = Path(relative)
    if entry.is_absolute() or ".." in entry.parts:
        return None
    root = base_dir.absolute()
    candidate = (root / entry).absolute()
    try:
        relative_candidate = candidate.relative_to(root)
    except ValueError:
        return None
    cursor = root
    for part in relative_candidate.parts:
        cursor = cursor / part
        if cursor.is_symlink():
            return None
    return candidate

def provider_scope(base_dir: Path, provider_override: str = None) -> str:
    provider = provider_override or load_config(resolve_config_path(base_dir)).get("active_provider", "all")
    return "antigravity" if provider == "agy" else provider

def output_provider(relative: str):
    path = Path(relative)
    if path.parts and path.parts[0] == ".codex":
        return "codex"
    if relative == "CLAUDE.md" or (path.parts and path.parts[0] == ".claude"):
        return "claude"
    if relative == "AGENTS.md" or (path.parts and path.parts[0] == ".agents"):
        return "antigravity"
    return None

def build_project_guardrails(project: dict) -> str:
    lines = []
    
    subsystems = project.get("subsystems", [])
    if subsystems:
        sub_desc = ", ".join([f"`{s['name']}` ({s.get('path', '')} — {s.get('stack', '')})" for s in subsystems])
        lines.append(f"- **Subsystem Boundaries**: {sub_desc}")
        lines.append("  * *Isolation Rule*: Never combine disjoint subsystems in one implementation slice.")
    
    forbidden = project.get("forbidden_paths", [])
    if forbidden:
        forb_desc = ", ".join([f"`{p}`" for p in forbidden])
        lines.append(f"- **Forbidden Build/Generated Paths**: {forb_desc}")
        lines.append("  * *Rule*: Strictly forbidden from manually editing, copying, diffing, or staging these paths.")
        
    build_sync = project.get("build_sync_cmd")
    if build_sync:
        lines.append(f"- **Deterministic Build Sync**: `{build_sync}` (Automated build command; never spawn an agent to manually patch build artifacts).")
        
    focused_test = project.get("focused_test_cmd", "npm test -- {file}")
    lines.append(f"- **Focused Unit Verification**: `{focused_test}` (Implementer must execute narrow tests to green before handoff).")
    
    full_test = project.get("full_test_cmd")
    if full_test:
        lines.append(f"- **Validation Suite**: `{full_test}` (Independent broader verification owned by code-validator).")
        
    build_cmd = project.get("build_cmd")
    if build_cmd:
        lines.append(f"- **Build / Package Verification**: `{build_cmd}` (Owned by code-validator).")
        
    return "\n".join(lines)

def interpolate_prompt(template_text: str, project: dict, guardrails_block: str) -> str:
    forbidden = project.get("forbidden_paths", [])
    forbidden_list = ", ".join([f"`{p}`" for p in forbidden]) if forbidden else "None"
    forbidden_globs = " ".join([f"--glob '!{p}'" for p in forbidden]) if forbidden else ""
    
    subsystems = project.get("subsystems", [])
    sub_names = " vs ".join([s["name"] for s in subsystems]) if subsystems else "different subsystems"
    sub_rule = f"Never combine {sub_names} in a single implementation slice unless verifying an explicit cross-stack contract test."
    
    replacements = {
        "{PROJECT_NAME}": project.get("name", "Project"),
        "{PROJECT_DESCRIPTION}": project.get("description", ""),
        "{PROJECT_GUARDRAILS}": guardrails_block,
        "{FORBIDDEN_PATHS_LIST}": forbidden_list,
        "{FORBIDDEN_PATHS_GLOB}": forbidden_globs,
        "{BUILD_SYNC_CMD}": project.get("build_sync_cmd", "npm run build"),
        "{FOCUSED_TEST_CMD}": project.get("focused_test_cmd", "npm test -- {file}"),
        "{FULL_TEST_CMD}": project.get("full_test_cmd", "npm test"),
        "{BUILD_CMD}": project.get("build_cmd", "npm run build"),
        "{SUBSYSTEMS_RULE}": sub_rule,
        "{SUBSYSTEMS_LIST}": sub_names,
    }
    
    text = template_text
    for placeholder, val in replacements.items():
        text = text.replace(placeholder, val)
    return text

def compile_codex(config: dict, project: dict, guardrails_block: str, base_dir: Path, agents_dir: Path) -> dict:
    """Compiles Codex configuration into .codex/config.toml and .codex/agents/*.toml. Returns map of file paths to contents."""
    codex_conf = config.get("codex", {})
    orch = codex_conf.get("orchestrator", {})
    agents_conf = provider_agents(config, "codex")
    
    outputs = {}
    codex_dir = base_dir / ".codex"
    out_agents_dir = codex_dir / "agents"
    
    protocol = compile_orchestrator_protocol(base_dir, project, guardrails_block)
    dev_instructions = f"""# Codex delegation adapter
Use `spawn_agent` with `fork_turns = "none"` and pass only the Compact Dispatch Contract.
Use `code-explorer` for targeted repository discovery and `diagnostician` for unknown-cause failures.

{protocol}
"""

    config_lines = [
        AUTO_GEN_HEADER_TOML,
        "# Root Orchestrator configuration",
        f'model = "{orch.get("model", "gpt-5.6-terra")}"',
        f'model_reasoning_effort = "{orch.get("reasoning_effort", "low")}"',
        f'plan_mode_reasoning_effort = "{orch.get("plan_mode_reasoning_effort", "medium")}"',
        f'tool_output_token_limit = {orch.get("tool_output_token_limit", 6000)}',
        f'model_auto_compact_token_limit = {orch.get("model_auto_compact_token_limit", 45000)}',
        f'model_auto_compact_token_limit_scope = "{orch.get("model_auto_compact_token_limit_scope", "body_after_prefix")}"',
        "",
        'developer_instructions = """',
        dev_instructions.strip(),
        '"""',
        "",
        "[features]",
        "multi_agent = true",
        ""
    ]
    
    agent_files = sorted(list(agents_dir.glob("*.md")))
    for afile in agent_files:
        if afile.name == ORCHESTRATOR_PROTOCOL.name:
            continue
        agent_name = afile.stem
        a_conf = agents_conf.get(agent_name, {})
        desc = a_conf.get("description", f"Agent: {agent_name}")
        model = a_conf.get("model", "gpt-5.6-luna")
        reasoning = a_conf.get("reasoning_effort", "low")
        
        config_lines.append(f"[agents.{agent_name}]")
        config_lines.append(f'description = "{desc}"')
        config_lines.append(f'config_file = "agents/{agent_name}.toml"\n')
        
        with open(afile, "r", encoding="utf-8") as f:
            template_text = f.read()
        compiled_instructions = interpolate_prompt(template_text, project, guardrails_block)
        
        agent_toml_lines = [
            AUTO_GEN_HEADER_TOML,
            f'name = "{agent_name}"',
            f'description = "{desc}"',
            f'model = "{model}"',
            f'model_reasoning_effort = "{reasoning}"'
        ]
        if agent_name == "commit-pusher":
            agent_toml_lines.append('sandbox_mode = "workspace-write"')
            
        agent_toml_lines.append('developer_instructions = """')
        agent_toml_lines.append(compiled_instructions.strip())
        agent_toml_lines.append('"""\n')
        
        outputs[out_agents_dir / f"{agent_name}.toml"] = "\n".join(agent_toml_lines)
        
    outputs[codex_dir / "config.toml"] = "\n".join(config_lines)
    return outputs

def compile_claude(config: dict, project: dict, guardrails_block: str,
                   base_dir: Path, agents_dir: Path) -> dict:
    """Compiles Claude Code configuration into CLAUDE.md and .claude/agents/*.md. Returns map of file paths to contents."""
    agents = provider_agents(config, "claude")
    protocol = compile_orchestrator_protocol(base_dir, project, guardrails_block)
    routing = "\n".join(
        f"- `{name}`: `{agent.get('model', 'inherit')}` "
        f"(thinking: `{agent.get('thinking', 'medium')}`)"
        for name, agent in agents.items()
    )
    claude_content = f"""{AUTO_GEN_HEADER_MD}
# Claude Code Delegation Adapter

Use Claude Code's native agent configuration in `.claude/agents/`.
Each generated agent file contains its canonical role instructions and model mapping.

{protocol}

## Claude Model Routing

{routing}
"""
    outputs = {base_dir / "CLAUDE.md": claude_content}

    for agent_path in sorted(agents_dir.glob("*.md")):
        role = agent_path.stem
        if role not in agents:
            continue
        model = agents[role].get("model", "inherit")
        effort = agents[role].get("thinking", "medium")
        description = (
            f"{role} agent for {config['project']['name']} "
            f"(reasoning effort: {effort})."
        )
        outputs[base_dir / f".claude/agents/{role}.md"] = (
            f"---\nname: {role}\ndescription: {description}\nmodel: {model}\n---\n\n"
            + interpolate_prompt(
                agent_path.read_text(encoding="utf-8"), project, guardrails_block
            )
        )
    return outputs


def compile_antigravity(config: dict, project: dict, guardrails_block: str,
                        base_dir: Path) -> dict:
    """Antigravity target: portable repository instructions and delegation syntax."""
    agents = provider_agents(config, "antigravity") or provider_agents(config, "agy")
    protocol = compile_orchestrator_protocol(base_dir, project, guardrails_block)
    routing = "\n".join(
        f"- `{name}`: model `{agent.get('model', 'flash')}`"
        for name, agent in agents.items()
    )
    agy_content = f"""{AUTO_GEN_HEADER_MD}
# Antigravity Delegation Adapter

{protocol}

## Antigravity Dispatch Syntax

When invoking `invoke_subagent`, set `TypeName: "self"` (or
`TypeName: "research"` for read-only exploration), `Role` to the
agent name, and `Model` according to this routing table. Include the
compact dispatch contract and instruct the subagent to adopt the matching
`agents/<role>.md` persona. Never send full conversation history.

{routing}
"""
    return {base_dir / "AGENTS.md": agy_content}

def compile_skills(project: dict, guardrails_block: str, base_dir: Path, skills_dir: Path, scope: str) -> dict:
    """Compile canonical skills for native discovery and explicit Codex prompts."""
    outputs = {}
    if not skills_dir.exists():
        return outputs
        
    for skill_path in skills_dir.iterdir():
        if not skill_path.is_dir():
            continue
        skill_name = skill_path.name
        
        for file_path in skill_path.rglob("*"):
            if not file_path.is_file():
                continue
            
            content = read_canonical_source(base_dir, file_path.relative_to(base_dir))
            content = interpolate_prompt(content, project, guardrails_block)
            rel_path = file_path.relative_to(skill_path)
            
            if file_path.name == "SKILL.md":
                parts = content.split("---", 2)
                if len(parts) >= 3:
                    frontmatter = f"---{parts[1]}---\n"
                    body = parts[2].lstrip()
                    content = f"{frontmatter}\n{AUTO_GEN_HEADER_MD}\n{body}"
                else:
                    content = f"{AUTO_GEN_HEADER_MD}\n{content}"
            
            if scope in ("all", "antigravity", "agy", "codex"):
                outputs[base_dir / ".agents" / "skills" / skill_name / rel_path] = content
            if scope in ("all", "claude"):
                outputs[base_dir / ".claude" / "skills" / skill_name / rel_path] = content
            if scope in ("all", "codex") and file_path.name == "SKILL.md" and rel_path == Path("SKILL.md"):
                outputs[base_dir / ".codex" / "prompts" / f"{skill_name}.md"] = content
                
    return outputs

def detect_project_stack(target_dir: Path) -> dict:
    """
    Inspects target_dir and detects project stack, build/test commands, and forbidden paths.
    Returns a dictionary suitable for generating .autonomous-dev-team.toml.
    """
    project_name = target_dir.resolve().name
    
    # 1. Check Node / TypeScript / JavaScript
    pkg_json_path = target_dir / "package.json"
    if pkg_json_path.exists():
        try:
            with open(pkg_json_path, "r", encoding="utf-8") as f:
                pkg_data = json.load(f)
        except Exception:
            pkg_data = {}
            
        desc = pkg_data.get("description") or "Node.js application"
        scripts = pkg_data.get("scripts", {})
        
        # Package manager detection
        if (target_dir / "pnpm-lock.yaml").exists():
            pm = "pnpm"
        elif (target_dir / "yarn.lock").exists():
            pm = "yarn"
        elif (target_dir / "bun.lockb").exists() or (target_dir / "bun.lock").exists():
            pm = "bun"
        else:
            pm = "npm"
            
        has_build = "build" in scripts
        has_test = "test" in scripts
        has_int_test = any(k in scripts for k in ["test:integration", "test:e2e", "integration", "test:all"])
        
        return {
            "name": project_name,
            "description": desc,
            "stack": "Node.js",
            "forbidden_paths": ["dist/**", "build/**", "coverage/**", "node_modules/**"],
            "build_sync_cmd": f"{pm} run build" if has_build else "",
            "focused_test_cmd": f"{pm} test -- {{file}}" if has_test else f"{pm} test",
            "full_test_cmd": f"{pm} run test:integration" if has_int_test else (f"{pm} test" if has_test else ""),
            "build_cmd": f"{pm} run build" if has_build else "",
            "subsystems": []
        }
        
    # 2. Check Rust
    cargo_path = target_dir / "Cargo.toml"
    if cargo_path.exists():
        return {
            "name": project_name,
            "description": "Rust application",
            "stack": "Rust",
            "forbidden_paths": ["target/**"],
            "build_sync_cmd": "cargo build",
            "focused_test_cmd": "cargo test -- {test_name}",
            "full_test_cmd": "cargo test",
            "build_cmd": "cargo build",
            "subsystems": []
        }

    # 3. Check Go
    go_mod_path = target_dir / "go.mod"
    if go_mod_path.exists():
        return {
            "name": project_name,
            "description": "Go application",
            "stack": "Go",
            "forbidden_paths": ["bin/**", "vendor/**"],
            "build_sync_cmd": "go build ./...",
            "focused_test_cmd": "go test -run {test_name} ./...",
            "full_test_cmd": "go test ./...",
            "build_cmd": "go build ./...",
            "subsystems": []
        }

    # 4. Check Python
    is_python = any((target_dir / p).exists() for p in [
        "pyproject.toml", "requirements.txt", "setup.py", "pytest.ini", "tox.ini"
    ]) or list(target_dir.glob("*.py"))
    
    if is_python:
        has_pytest = (target_dir / "pytest.ini").exists() or (target_dir / "conftest.py").exists()
        focused_cmd = "python3 -m pytest {file}" if has_pytest else "python3 -m unittest {file}"
        full_cmd = "pytest" if has_pytest else "python3 -m unittest discover tests"
        
        return {
            "name": project_name,
            "description": "Python application",
            "stack": "Python",
            "forbidden_paths": [".git/**", "__pycache__/**", "dist/**", "build/**", ".venv/**", ".pytest_cache/**"],
            "build_sync_cmd": "",
            "focused_test_cmd": focused_cmd,
            "full_test_cmd": full_cmd,
            "build_cmd": "python3 -m compileall .",
            "subsystems": []
        }

    # 5. Default generic fallback
    return {
        "name": project_name,
        "description": "Software project",
        "stack": "Generic",
        "forbidden_paths": ["dist/**", "build/**", ".cache/**"],
        "build_sync_cmd": "",
        "focused_test_cmd": "make test",
        "full_test_cmd": "make test",
        "build_cmd": "make build",
        "subsystems": []
    }

def generate_project_config_toml(stack_info: dict, source_dir: Path = None, active_provider: str = "all") -> str:
    """Tailor the canonical config's project section using TOML-safe values."""
    base_dir = source_dir or resolve_base_dir()
    canonical = read_canonical_source(base_dir, Path(CONFIG_NAME))
    
    provider_val = "antigravity" if active_provider == "agy" else active_provider
    lines = canonical.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("active_provider ="):
            lines[i] = f'active_provider = "{provider_val}"\n'
            break
    canonical = "".join(lines)
    
    tomllib.loads(canonical)
    values = {
        "name": stack_info.get("name", "project"),
        "description": stack_info.get("description", "Autonomous Multi-Agent Repository"),
        "forbidden_paths": stack_info.get("forbidden_paths", []),
        "build_sync_cmd": stack_info.get("build_sync_cmd", ""),
        "focused_test_cmd": stack_info.get("focused_test_cmd", "npm test -- {file}"),
        "full_test_cmd": stack_info.get("full_test_cmd", "npm test"),
        "build_cmd": stack_info.get("build_cmd", ""),
    }
    lines = canonical.splitlines(keepends=True)
    project_start = next((i for i, line in enumerate(lines) if line.strip() == "[project]"), None)
    if project_start is None:
        raise ValueError(f"Canonical {CONFIG_NAME} is missing [project]")
    project_end = next(
        (i for i in range(project_start + 1, len(lines)) if lines[i].strip().startswith("[")),
        len(lines),
    )
    replacements = []
    for key, value in values.items():
        starts = [
            i for i in range(project_start + 1, project_end)
            if lines[i].split("=", 1)[0].strip() == key and "=" in lines[i]
        ]
        if len(starts) != 1:
            raise ValueError(f"Canonical {CONFIG_NAME} must define [project].{key} exactly once")
        start = starts[0]
        end = None
        for candidate_end in range(start + 1, project_end + 1):
            try:
                parsed = tomllib.loads("[project]\n" + "".join(lines[start:candidate_end]))
            except tomllib.TOMLDecodeError:
                continue
            if key in parsed.get("project", {}):
                end = candidate_end
                break
        if end is None:
            raise ValueError(f"Canonical {CONFIG_NAME} has an invalid [project].{key} assignment")
        replacements.append((start, end, f"{key} = {json.dumps(value, ensure_ascii=False)}\n"))
    for start, end, replacement in reversed(replacements):
        lines[start:end] = [replacement]
    rendered = "".join(lines)
    tomllib.loads(rendered)
    return rendered

def generate_all_outputs(base_dir: Path, provider_override: str = None) -> dict:
    """Generates a dict of Path -> content for all target provider files without writing them to disk."""
    config_path = resolve_config_path(base_dir)
    agents_dir = resolve_agents_dir(base_dir)
    config = load_config(config_path)
    project = config.get("project", {})
    provider = provider_override or config.get("active_provider", "all")
    
    guardrails_block = build_project_guardrails(project)
    
    all_outputs = {}
    if provider in ("all", "codex"):
        all_outputs.update(compile_codex(config, project, guardrails_block, base_dir, agents_dir))
    if provider in ("all", "claude"):
        all_outputs.update(compile_claude(config, project, guardrails_block, base_dir, agents_dir))
    if provider in ("all", "antigravity", "agy"):
        all_outputs.update(compile_antigravity(config, project, guardrails_block, base_dir))
        
    skills_dir = resolve_skills_dir(base_dir)
    all_outputs.update(compile_skills(project, guardrails_block, base_dir, skills_dir, provider))
        
    return all_outputs

def run_sync(base_dir: Path, provider_override: str = None):
    """Synchronizes all target provider configurations, writes generated files, prunes stale artifacts, and updates the manifest."""
    print("Synchronizing Multi-Provider Autonomous Agent Protocol...")
    outputs = generate_all_outputs(base_dir, provider_override)
    manifest_path = resolve_manifest_path(base_dir)
    previous = []
    if manifest_path.exists():
        try:
            previous = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            previous = []
    elif (base_dir / MANIFEST_NAME).exists():
        try:
            previous = json.loads((base_dir / MANIFEST_NAME).read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            previous = []
    current = {str(path.relative_to(base_dir)) for path in outputs}
    scope = provider_scope(base_dir, provider_override)
    preserved = set() if scope == "all" else {
        path for path in previous if output_provider(path) != scope
    }
    for relative in sorted(set(previous) - current - preserved):
        stale = managed_path(base_dir, relative)
        if stale and stale.is_file() and "AUTO-GENERATED BY sync.py" in stale.read_text(encoding="utf-8"):
            stale.unlink()
    
    codex_agent_count = 0
    claude_updated = False
    antigravity_updated = False
    
    for fpath, content in outputs.items():
        fpath.parent.mkdir(parents=True, exist_ok=True)
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(content)
        if ".codex/agents" in fpath.as_posix():
            codex_agent_count += 1
        elif fpath.name == "CLAUDE.md":
            claude_updated = True
        elif fpath.name == "AGENTS.md":
            antigravity_updated = True
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps({"schema": SCHEMA_NAME, "version": SCHEMA_VERSION,
                                         "files": sorted(current | preserved)}, indent=2) + "\n", encoding="utf-8")
    if manifest_path != (base_dir / MANIFEST_NAME) and (base_dir / MANIFEST_NAME).is_file():
        try:
            (base_dir / MANIFEST_NAME).unlink()
        except OSError:
            pass
            
    if codex_agent_count > 0:
        print(f"  ✓ Codex: Compiled {codex_agent_count} agents into .codex/")
    if claude_updated:
        print("  ✓ Claude Code: Generated CLAUDE.md")
    if antigravity_updated:
        print("  ✓ Antigravity: Generated AGENTS.md")
    
    skills_count = sum(1 for p in current if "/skills/" in str(p) or "/prompts/" in str(p))
    if skills_count > 0:
        print(f"  ✓ Skills: Compiled canonical skills to providers")

    for candidate in (
        base_dir / ENCAPSULATED_DIR_NAME / "__pycache__",
        base_dir / ENCAPSULATED_DIR_NAME / INTERNAL_DIR_NAME / "__pycache__",
    ):
        if candidate.is_dir() and not candidate.is_symlink():
            try:
                shutil.rmtree(candidate)
            except OSError:
                pass

    print("✓ Synchronization complete.\n")

def run_check(base_dir: Path, provider_override: str = None, quiet: bool = False) -> int:
    """Checks generated files and their ownership manifest. Returns 0 if matching."""
    outputs = generate_all_outputs(base_dir, provider_override)
    mismatched = []
    missing = []
    stale = []
    
    for fpath, expected_content in outputs.items():
        if not fpath.exists():
            missing.append(fpath.relative_to(base_dir))
        else:
            with open(fpath, "r", encoding="utf-8") as f:
                actual_content = f.read()
            if actual_content != expected_content:
                mismatched.append(fpath.relative_to(base_dir))
    manifest_path = resolve_manifest_path(base_dir)
    if not manifest_path.exists():
        fallback = base_dir / MANIFEST_NAME
        if fallback.exists():
            manifest_path = fallback
        else:
            missing.append(manifest_path.relative_to(base_dir))
    if manifest_path.exists():
        try:
            owned = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
        except (OSError, ValueError, TypeError):
            owned = []
        expected = {str(path.relative_to(base_dir)) for path in outputs}
        scope = provider_scope(base_dir, provider_override)
        stale = [Path(path) for path in owned
                 if path not in expected and (scope == "all" or output_provider(path) == scope)
                 and managed_path(base_dir, path)
                 and managed_path(base_dir, path).exists()]
                
    if not missing and not mismatched and not stale:
        if not quiet:
            print(f"✓ All provider configurations are in sync with {CONFIG_NAME} and agents/.")
        return 0
    else:
        if not quiet:
            print("Error: Provider configurations are out of sync!")
            if missing:
                print("  Missing files:")
                for m in missing:
                    print(f"    - {m}")
            if mismatched:
                print("  Out-of-date files:")
                for m in mismatched:
                    print(f"    - {m}")
            if stale:
                print("  Stale managed files:")
                for item in stale:
                    print(f"    - {item}")
            print("\nRun './sync.py' to regenerate provider files.")
        return 1

