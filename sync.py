def build_trampoline_args(target_py, argv):
    """Constructs execv args for Python trampoline, handling '-m' module rewriting."""
    if not argv or argv[0] == "-c":
        return None
    args = [target_py]
    if " -m " in argv[0]:
        parts = argv[0].split(" -m ", 1)
        args.extend(["-m", parts[1]])
        args.extend(argv[1:])
    else:
        args.extend(argv)
    return args


